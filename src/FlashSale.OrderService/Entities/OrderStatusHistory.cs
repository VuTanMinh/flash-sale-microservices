using System;

namespace FlashSale.OrderService.Entities;

/// <summary>
/// Append-only record of every order state change (Week 11 box 2, TP-P02,
/// docs/order-state-machine.md "State history"). A row is written in the same
/// transaction as the state change it records, so the history can never
/// disagree with <see cref="Order.State"/>.
///
/// The creation row has <see cref="FromState"/> = null and
/// <see cref="MessageId"/> = null (no event triggered it); it is written in the
/// API's order + Outbox transaction. Every applied transition adds one row with
/// its triggering broker <see cref="MessageId"/>. A no-op (an event that is
/// acknowledged because the order is already in, or past, the target state)
/// writes no history row.
///
/// Plain class, not an ABP AggregateRoot, for the same reason as
/// <see cref="Order"/> (see its doc comment).
/// </summary>
public class OrderStatusHistory
{
    public Guid Id { get; private set; }

    /// <summary>
    /// Database-assigned insertion-order key (Week 11 box 2 review R1). Every
    /// history read is ordered by this, not by <see cref="At"/> then <see cref="Id"/>,
    /// because <see cref="At"/> can arrive out of order (the Worker can start
    /// before Order Service records Confirmed) and <see cref="Id"/> is a random
    /// Guid. In PostgreSQL this is a <c>bigint GENERATED BY DEFAULT AS IDENTITY</c>
    /// column; the SQLite-backed unit tests assign it client-side.
    /// </summary>
    public long Seq { get; private set; }

    public Guid OrderId { get; private set; }

    /// <summary>The state the order left (null for the creation row).</summary>
    public OrderState? FromState { get; private set; }

    /// <summary>The state the order entered.</summary>
    public OrderState ToState { get; private set; }

    /// <summary>
    /// The triggering broker message's MessageId, or null for the creation row.
    /// For an implied <c>Processing</c> row (see StockResultProcessor) this is
    /// the <c>OrderProcessed</c> message id (the OrderId), because that is the
    /// event that caused the implied transition.
    /// </summary>
    public Guid? MessageId { get; private set; }

    /// <summary>
    /// When the order entered <see cref="ToState"/>. For the implied
    /// <c>Processing</c> row this is the later of the Worker's start time
    /// (carried on <c>OrderProcessed.ProcessingStartedAt</c>) and the order's
    /// confirmation time — the Worker can start before Order Service records
    /// Confirmed, and the history time must never go backwards (review R1). For
    /// every other row it is the time the transition was applied.
    /// </summary>
    public DateTime At { get; private set; }

    /// <summary>
    /// True only for the <c>Processing</c> row written when an
    /// <c>OrderProcessed</c> arrives while the order is still <c>Confirmed</c>
    /// (the started event has not arrived): the <c>Confirmed → Processing →
    /// Completed</c> legs are applied in one transaction, and the middle
    /// <c>Processing</c> step is recorded as implied rather than observed.
    /// </summary>
    public bool Implied { get; private set; }

    private OrderStatusHistory()
    {
        // EF Core materialization only.
    }

    public OrderStatusHistory(
        Guid id, Guid orderId, OrderState? fromState, OrderState toState, Guid? messageId, DateTime at, bool implied)
    {
        Id = id;
        OrderId = orderId;
        FromState = fromState;
        ToState = toState;
        MessageId = messageId;
        At = at;
        Implied = implied;
    }
}
